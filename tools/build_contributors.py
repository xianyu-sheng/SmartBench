#!/usr/bin/env python3
"""Render the public data-contributor leaderboard from the consent ledger."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "trajectories" / "v0" / "consent.json"
OUTPUT = ROOT / "trajectories" / "CONTRIBUTORS.md"

HEADER = """# Data contributors

SmartBench publishes third-party audit trajectories only with **explicit written
consent**. This leaderboard lists repository owners who granted permission; a
pending request is not listed and does not imply endorsement.

| Contributor / repository | Data contribution | Trajectories | Consented |
|---|---|---|---|
"""

FOOTER = """
Listing is opt-in: a maintainer can ask for a display name or no listing. To be
listed, grant consent using the process in [`CONSENT.md`](CONSENT.md). The
trajectory data itself is in [`v0/`](v0/).

_Generated by `tools/build_contributors.py`; do not edit by hand._
"""


def render(ledger: Dict[str, Any]) -> str:
    rows: List[str] = []
    cases = [
        case
        for case in ledger.get("cases", [])
        if isinstance(case, dict)
        and case.get("status") == "granted"
        and case.get("listed", True)
    ]
    cases.sort(key=lambda case: str(case.get("granted_at", "")), reverse=True)
    for case in cases:
        repository = str(case.get("repository", ""))
        name = str(case.get("display_name") or repository)
        if repository:
            label = f"[{name}](https://github.com/{repository})"
        else:
            label = name
        contribution = str(
            case.get("contribution")
            or "Redacted audit trajectory and verification summary"
        )
        trajectories = ", ".join(
            f"`{item}`" for item in (case.get("trajectory_ids") or [])
        ) or "—"
        consented = str(case.get("granted_at") or "—")
        rows.append(f"| {label} | {contribution} | {trajectories} | {consented} |")
    if not rows:
        rows.append("| _No third-party data contributors yet._ | — | — | — |")
    return HEADER + "\n".join(rows) + "\n" + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ledger", default=str(LEDGER))
    parser.add_argument("--output", default=str(OUTPUT))
    parser.add_argument("--check", action="store_true", help="Fail if the file is stale")
    args = parser.parse_args()
    ledger = json.loads(Path(args.ledger).read_text(encoding="utf-8"))
    rendered = render(ledger)
    output = Path(args.output)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != rendered:
            print(f"{output} is stale; run tools/build_contributors.py", file=sys.stderr)
            return 1
        return 0
    output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
