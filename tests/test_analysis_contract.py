"""Regression tests for capability contracts and source provenance."""

from pathlib import Path

from smartbench.core import (
    AdapterRegistry,
    RuleRegistry,
    UnifiedDiagnosticConfig,
    UnifiedDiagnosticEngine,
)
from smartbench.core.adapters import GoAdapter, PythonAdapter
from smartbench.core.rules.base import DiagnosticRule, Finding, Location, Severity
from smartbench.graph.builder import CodeGraphBuilder
from smartbench.graph.schema import CodeGraph, CodeNode, NodeType
from smartbench.ir import (
    Capability,
    CapabilityLevel,
    CapabilitySet,
    RepositoryZone,
    SemanticIR,
    SourceRole,
    classify_repository_zone,
    classify_source_role,
)


def test_capability_contract_distinguishes_partial_from_unsupported():
    capabilities = CapabilitySet.from_values(
        "typescript",
        [Capability.STRUCTURE],
        partial={Capability.DATA_FLOW: "intra-procedural taint"},
    )

    partial = capabilities.assess({Capability.DATA_FLOW: CapabilityLevel.PARTIAL})
    full = capabilities.assess({Capability.DATA_FLOW: CapabilityLevel.FULL})

    assert partial["status"] == CapabilityLevel.PARTIAL.value
    assert partial["capabilities"]["data_flow"]["actual"] == CapabilityLevel.PARTIAL.value
    assert full["status"] == CapabilityLevel.UNSUPPORTED.value


def test_source_role_classifier_is_repository_agnostic():
    assert classify_source_role("src/service.py")[0] == SourceRole.PRODUCTION
    assert classify_source_role("tests/test_service.py")[0] == SourceRole.TEST
    assert classify_source_role("evals/tracker.eval.ts")[0] == SourceRole.FIXTURE
    assert classify_source_role("examples/demo.py")[0] == SourceRole.EXAMPLE
    assert classify_source_role("src/generated/client.py")[0] == SourceRole.GENERATED
    assert classify_source_role("README.md")[0] == SourceRole.DOCUMENTATION
    assert classify_source_role("src/client.py", "# Code generated by tool; DO NOT EDIT")[0] == SourceRole.GENERATED


def test_repository_zone_is_separate_from_source_role():
    role, _ = classify_source_role("legacy/service.py")
    zone, reason = classify_repository_zone("legacy/service.py", role=role)
    assert role == SourceRole.PRODUCTION
    assert zone == RepositoryZone.LEGACY
    assert reason == "legacy path convention"

    zone, _ = classify_repository_zone("vendor/client.py")
    assert zone == RepositoryZone.VENDORED


def test_engine_scan_plan_walks_once_and_partitions_languages(tmp_path: Path, monkeypatch):
    (tmp_path / "app.py").write_text("value = 1\n", encoding="utf-8")
    (tmp_path / "main.go").write_text("package main\n", encoding="utf-8")
    (tmp_path / "notes.txt").write_text("ignored\n", encoding="utf-8")

    adapters = AdapterRegistry()
    adapters.register(PythonAdapter())
    adapters.register(GoAdapter())
    engine = UnifiedDiagnosticEngine(adapters, RuleRegistry())

    calls = []
    original = CodeGraphBuilder.discover_files_for_extensions

    def counted(self, root, extensions, file_filter=None):
        calls.append((root, set(extensions)))
        return original(self, root, extensions, file_filter)

    monkeypatch.setattr(CodeGraphBuilder, "discover_files_for_extensions", counted)
    plan = engine._plan_frontend_files(
        tmp_path,
        ["python", "go"],
        UnifiedDiagnosticConfig(max_files=10),
    )

    assert len(calls) == 1
    assert [path.name for path in plan["python"]] == ["app.py"]
    assert [path.name for path in plan["go"]] == ["main.go"]

    empty = engine._plan_frontend_files(
        tmp_path,
        ["python", "go"],
        UnifiedDiagnosticConfig(file_paths=[]),
    )
    assert empty == {"python": [], "go": []}


def test_semantic_ir_uses_generated_header_provenance(tmp_path: Path):
    source = tmp_path / "client.py"
    source.write_text(
        "# Code generated by schema tool; DO NOT EDIT\nvalue = 1\n",
        encoding="utf-8",
    )

    ir = PythonAdapter().parse_semantic_project(tmp_path)

    assert ir.source_units["client.py"].role == SourceRole.GENERATED
    assert ir.source_units["client.py"].role_reason == "generated-file marker"
    assert ir.source_units["client.py"].repository_zone == RepositoryZone.GENERATED


class _SourceRoleRule(DiagnosticRule):
    @property
    def rule_id(self):
        return "source_role_contract"

    @property
    def rule_name(self):
        return "Source Role Contract"

    @property
    def supported_languages(self):
        return {"python"}

    @property
    def source_roles(self):
        return {SourceRole.PRODUCTION, SourceRole.UNKNOWN}

    def analyze(self, ir):
        return [
            Finding(
                rule_id=self.rule_id,
                rule_name=self.rule_name,
                severity=Severity.WARNING,
                location=Location(path, 1),
                message="candidate",
            )
            for path in ("app.py", "tests/test_app.py")
        ]


class _StaticPythonAdapter(PythonAdapter):
    """Small adapter fixture that keeps test units in the semantic IR."""

    def parse_semantic_project(self, project_path, file_paths=None):
        graph = CodeGraph(meta={"project_path": str(project_path)})
        for index, path in enumerate(("app.py", "tests/test_app.py")):
            graph.add_node(
                CodeNode(
                    id=f"node-{index}",
                    node_type=NodeType.FUNCTION,
                    name="candidate",
                    file_path=path,
                    line_start=1,
                    line_end=1,
                    language="python",
                )
            )
        return SemanticIR.from_graph(
            graph,
            language="python",
            project_path=str(project_path),
        )


def test_engine_records_contract_status_and_excludes_nonproduction_findings(tmp_path: Path):
    (tmp_path / "app.py").write_text("value = 1\n", encoding="utf-8")
    (tmp_path / "tests").mkdir()
    (tmp_path / "tests" / "test_app.py").write_text("value = 1\n", encoding="utf-8")

    adapters = AdapterRegistry()
    adapters.register(_StaticPythonAdapter())
    rules = RuleRegistry()
    rules.register(_SourceRoleRule())
    result = UnifiedDiagnosticEngine(adapters, rules).diagnose(
        tmp_path,
        UnifiedDiagnosticConfig(build_evidence_packs=False),
    )

    assert [finding.location.file_path for finding in result.findings] == ["app.py"]
    assert result.findings[0].metadata["source_role"] == SourceRole.PRODUCTION.value
    status = result.analysis_status["source_role_contract"]
    # A rule with no declared semantic requirements is not evidence of full
    # frontend support.  Its capability coverage is explicitly unknown.
    assert status["status"] == CapabilityLevel.UNKNOWN.value
    assert status["analysis_method"] == "unknown"
    assert status["excluded_findings"] == 1
