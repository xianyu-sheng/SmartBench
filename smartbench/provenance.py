"""Deterministic source provenance shared by discovery, IR, and rules."""

from __future__ import annotations

from enum import Enum
from pathlib import PurePath
from typing import Optional


class SourceRole(str, Enum):
    """Role a source unit plays in a repository."""

    PRODUCTION = "production"
    TEST = "test"
    FIXTURE = "fixture"
    EXAMPLE = "example"
    GENERATED = "generated"
    DOCUMENTATION = "documentation"
    UNKNOWN = "unknown"


class RepositoryZone(str, Enum):
    """Where a source unit sits in the repository ownership boundary."""

    FIRST_PARTY = "first_party"
    LEGACY = "legacy"
    THIRD_PARTY = "third_party"
    VENDORED = "vendored"
    GENERATED = "generated"
    UNKNOWN = "unknown"


_TEST_PARTS = {"test", "tests", "__tests__", "testdata", "spec", "specs"}
_FIXTURE_PARTS = {
    "fixture",
    "fixtures",
    "__fixtures__",
    "eval",
    "evals",
    "benchmark",
    "benchmarks",
    "snapshots",
}
_EXAMPLE_PARTS = {"example", "examples", "sample", "samples", "demo", "demos"}
_DOC_PARTS = {"doc", "docs", "documentation"}
_GENERATED_PARTS = {"generated", "gen", "dist", "build", "out"}
_LEGACY_PARTS = {"legacy", "deprecated", "archive", "archived"}
_THIRD_PARTY_PARTS = {"third_party", "third-party", "external", "externals"}
_VENDORED_PARTS = {"vendor", "vendored", "node_modules", "site-packages"}
_DOC_SUFFIXES = {".md", ".mdx", ".rst", ".adoc", ".txt"}


def classify_source_role(
    file_path: str,
    content: Optional[str] = None,
) -> tuple[SourceRole, str]:
    """Classify a path using stable conventions and return an explanation.

    Generated markers are checked before directory names because generated
    code can live under an otherwise production-looking package.  A normal
    source file defaults to ``production``; ``unknown`` is reserved for an
    empty or malformed path.
    """

    normalized = file_path.replace("\\", "/").strip("/")
    if not normalized:
        return SourceRole.UNKNOWN, "empty source path"
    path = PurePath(normalized)
    parts = {part.lower() for part in path.parts[:-1]}
    name = path.name.lower()
    suffix = path.suffix.lower()

    if content and _has_generated_marker(content):
        return SourceRole.GENERATED, "generated-file marker"
    if parts & _GENERATED_PARTS or ".generated." in name or name.endswith("_generated.go"):
        return SourceRole.GENERATED, "generated path convention"
    if suffix in _DOC_SUFFIXES or parts & _DOC_PARTS:
        return SourceRole.DOCUMENTATION, "documentation path or extension"
    if parts & _FIXTURE_PARTS:
        return SourceRole.FIXTURE, "fixture/evaluation path convention"
    if parts & _TEST_PARTS or _looks_like_test_file(name):
        return SourceRole.TEST, "test path convention"
    if parts & _EXAMPLE_PARTS or _looks_like_example_file(name):
        return SourceRole.EXAMPLE, "example path convention"
    return SourceRole.PRODUCTION, "default source path"


def _looks_like_test_file(name: str) -> bool:
    stem = name.rsplit(".", 1)[0] if "." in name else name
    return (
        stem.startswith("test_")
        or stem.endswith("_test")
        or stem.endswith("_spec")
        or stem.startswith("spec_")
    )


def _looks_like_example_file(name: str) -> bool:
    stem = name.rsplit(".", 1)[0] if "." in name else name
    return stem.startswith("example_") or stem.startswith("sample_")


def _has_generated_marker(content: str) -> bool:
    for line in content.splitlines()[:8]:
        lowered = line.lower().strip()
        if "code generated" in lowered and "do not edit" in lowered:
            return True
        if "automatically generated" in lowered or "generated by" in lowered:
            return True
    return False


def classify_repository_zone(
    file_path: str,
    content: Optional[str] = None,
    role: SourceRole | None = None,
) -> tuple[RepositoryZone, str]:
    """Classify repository ownership independently from source role.

    ``SourceRole.PRODUCTION`` only describes how a file is used (as opposed
    to a test or fixture).  A legacy production file must still be visible as
    legacy, not silently counted as current first-party production code.
    """
    normalized = file_path.replace("\\", "/").strip("/")
    if not normalized:
        return RepositoryZone.UNKNOWN, "empty source path"
    path = PurePath(normalized)
    parts = {part.lower() for part in path.parts[:-1]}
    name = path.name.lower()
    if role == SourceRole.GENERATED or parts & _GENERATED_PARTS or ".generated." in name:
        return RepositoryZone.GENERATED, "generated path or source role"
    if parts & _VENDORED_PARTS:
        return RepositoryZone.VENDORED, "vendored dependency path convention"
    if parts & _THIRD_PARTY_PARTS:
        return RepositoryZone.THIRD_PARTY, "third-party path convention"
    if parts & _LEGACY_PARTS:
        return RepositoryZone.LEGACY, "legacy path convention"
    return RepositoryZone.FIRST_PARTY, "default repository ownership"
