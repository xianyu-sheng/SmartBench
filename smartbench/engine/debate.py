"""
Generic multi-model debate engine — no project-specific hardcoding.

Three roles:
1. Proposer — analyzes context and proposes fixes
2. Critique — reviews proposals for risks
3. Judge — synthesizes into final recommendations

All prompts are generated by PromptFactory based on ProjectFingerprint.
"""

import json
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional

from smartbench.detector.fingerprint import ProjectFingerprint
from smartbench.llm.client import parse_json_safe
from smartbench.prompts.factory import PromptFactory


@dataclass
class DebateResult:
    """Structured result from a debate round."""
    final_suggestions: List[Dict[str, Any]] = field(default_factory=list)
    debate_log: List[Dict[str, Any]] = field(default_factory=list)
    consensus_reached: bool = False
    iterations: int = 0
    total_tokens_used: int = 0
    duration_ms: int = 0


@dataclass
class ModelResponse:
    """Response from a single model call."""
    model_name: str
    role: str
    content: str
    success: bool
    error: Optional[str] = None
    tokens_used: int = 0


class DebateEngine:
    """
    Generic multi-model debate engine with optional evidence verification.

    Usage:
        factory = PromptFactory(fingerprint)
        verifier = Verifier(project_path, graph, retriever)  # optional
        engine = DebateEngine(llm_call_fn, factory, verifier=verifier)
        result = engine.debate(analysis_context, target="Improve performance")
    """

    def __init__(
        self,
        llm_call_fn: Callable[[str], str],
        prompt_factory: Optional[PromptFactory] = None,
        fingerprint: Optional[ProjectFingerprint] = None,
        max_call_attempts: int = 2,
        timeout_per_call: int = 60,
        verifier: Optional[Any] = None,
    ):
        """
        Args:
            llm_call_fn: Function that takes a prompt string and returns response text
            prompt_factory: PromptFactory instance (created from fingerprint)
            fingerprint: ProjectFingerprint (used to create factory if not provided)
            max_call_attempts: Maximum attempts for each role call
            timeout_per_call: Timeout forwarded to timeout-aware LLM callables
            verifier: Optional Verifier for evidence-based claim checking
        """
        self.llm_call = llm_call_fn
        # Fix: operator precedence — 'or ... if ... else' binds as (or ...) if ... else
        if prompt_factory is not None:
            self.factory = prompt_factory
        elif fingerprint is not None:
            self.factory = PromptFactory(fingerprint)
        else:
            self.factory = None
        self.max_call_attempts = max(1, max_call_attempts)
        self.timeout = timeout_per_call
        self.verifier = verifier  # NEW: evidence verification layer
        self._last_call_error: Optional[str] = None

    def debate(
        self,
        analysis_context: str,
        target: str = "Identify and fix the most impactful issues",
        model_name: str = "default",
        on_progress: callable = None,
        strategy: str = "",
    ) -> DebateResult:
        """
        Run a full debate cycle.

        Args:
            analysis_context: Built by PromptFactory.build_analysis_context()
            target: What we're trying to achieve
            model_name: Name of the model being used (for logging)
            on_progress: Optional callback(role, parsed_json, raw_text) after each round

        Returns:
            DebateResult with final suggestions
        """
        if not self.factory:
            raise RuntimeError("DebateEngine requires a PromptFactory. "
                             "Pass one to __init__ or provide a fingerprint.")

        start_time = time.time()
        log: List[Dict[str, Any]] = []
        total_chars = 0  # approximate token count: chars / 3

        # ── Round 1: Proposer ─────────────────────────────────────────
        proposer_prompt = self.factory.build_proposer_prompt(
            analysis_context, target, strategy=strategy,
        )
        proposer_raw, proposer_json = self._safe_json_call(
            proposer_prompt,
            model_name,
            role="proposer",
            required_list_field="proposals",
        )
        total_chars += len(proposer_prompt) + len(proposer_raw or "")
        proposer_log = {"role": "proposer", "input": proposer_prompt[:500],
                        "output": proposer_raw[:500] if proposer_raw else ""}
        if self._last_call_error:
            proposer_log["error"] = self._last_call_error
        log.append(proposer_log)
        self._emit_progress(
            on_progress, "proposer", proposer_json, proposer_raw, log
        )

        if not proposer_json:
            return DebateResult(
                debate_log=log,
                final_suggestions=[],
                duration_ms=int((time.time() - start_time) * 1000),
                total_tokens_used=total_chars // 3,
            )

        # ── Round 1.5: Verify Proposer claims ── (NEW)
        verification_summary = ""
        if self.verifier:
            try:
                proposals = proposer_json.get("proposals", [])
                if proposals:
                    verified_proposals = self.verifier.verify_proposals(proposals)
                    proposer_json["proposals"] = verified_proposals
                    # Build human-readable verification summary
                    verification_summary = self.verifier.build_summary(
                        verified_proposals
                    )
                    log.append({
                        "role": "verifier",
                        "type": "proposer_check",
                        "verification_summary": verification_summary[:500],
                    })
                    self._emit_progress(
                        on_progress,
                        "verifier",
                        {
                            "type": "proposer_check",
                            "proposals": verified_proposals,
                            "summary": verification_summary,
                        },
                        None,
                        log,
                    )
                    total_chars += len(verification_summary)
            except Exception as e:
                log.append({
                    "role": "verifier",
                    "error": self._format_call_error(e),
                })
                verification_summary = ""

        # ── Round 2: Critique (with verification context) ─────────────
        critique_prompt = self.factory.build_critique_prompt(
            json.dumps(proposer_json, ensure_ascii=False, indent=2),
            analysis_context,
            verification_summary=verification_summary,
        )
        critique_raw, critique_json = self._safe_json_call(
            critique_prompt,
            model_name,
            role="critique",
            required_list_field="verdicts",
        )
        total_chars += len(critique_prompt) + len(critique_raw or "")
        critique_log = {"role": "critique", "input": critique_prompt[:500],
                        "output": critique_raw[:500] if critique_raw else ""}
        if self._last_call_error:
            critique_log["error"] = self._last_call_error
        log.append(critique_log)
        self._emit_progress(
            on_progress, "critique", critique_json, critique_raw, log
        )

        # ── Round 2.5: Verify Critique claims ── (NEW)
        if self.verifier and critique_json:
            try:
                verified_critique = self.verifier.verify_critique(
                    critique_json,
                    proposer_json.get("proposals", []),
                )
                critique_json = verified_critique
                log.append({
                    "role": "verifier",
                    "type": "critique_check",
                })
            except Exception as e:
                log.append({
                    "role": "verifier",
                    "error": self._format_call_error(e),
                })

        # ── Round 3: Judge (with full verification trail) ──────────────
        judge_prompt = self.factory.build_judge_prompt(
            json.dumps(proposer_json, ensure_ascii=False, indent=2),
            json.dumps(critique_json, ensure_ascii=False, indent=2) if critique_json else "{}",
            analysis_context,
            verification_summary=verification_summary,
        )
        judge_raw, judge_json = self._safe_json_call(
            judge_prompt,
            model_name,
            role="judge",
            required_list_field="final_suggestions",
        )
        total_chars += len(judge_prompt) + len(judge_raw or "")
        judge_log = {"role": "judge", "input": judge_prompt[:500],
                     "output": judge_raw[:500] if judge_raw else ""}
        if self._last_call_error:
            judge_log["error"] = self._last_call_error
        log.append(judge_log)
        self._emit_progress(on_progress, "judge", judge_json, judge_raw, log)

        # ── Extract final suggestions with final verification ────────
        final_suggestions = []
        if judge_json:
            final_suggestions = judge_json.get("final_suggestions", [])
            # Final verification pass on accepted suggestions
            if self.verifier and final_suggestions:
                try:
                    final_suggestions = self.verifier.verify_proposals(
                        final_suggestions
                    )
                except Exception as exc:
                    log.append({
                        "role": "verifier",
                        "type": "final_check",
                        "error": self._format_call_error(exc),
                    })
        elif proposer_json:
            # Fallback: use proposer suggestions directly if judge fails
            final_suggestions = proposer_json.get("proposals", [])
            if self.verifier and final_suggestions:
                try:
                    final_suggestions = self.verifier.verify_proposals(
                        final_suggestions
                    )
                except Exception as exc:
                    log.append({
                        "role": "verifier",
                        "type": "fallback_check",
                        "error": self._format_call_error(exc),
                    })

        elapsed = int((time.time() - start_time) * 1000)

        return DebateResult(
            final_suggestions=final_suggestions,
            debate_log=log,
            consensus_reached=judge_json is not None,
            iterations=3,
            total_tokens_used=total_chars // 3,
            duration_ms=elapsed,
        )

    # ── Helpers ───────────────────────────────────────────────────────

    def _safe_call(self, prompt: str, model_name: str, role: str = "") -> str:
        """Call an LLM safely, forwarding role and timeout when supported."""
        self._last_call_error = None
        for _attempt in range(self.max_call_attempts):
            try:
                response = self._invoke_llm(prompt, role)
                if response:
                    self._last_call_error = None
                    return response
                self._last_call_error = "LLM returned an empty response"
            except Exception as exc:
                self._last_call_error = self._format_call_error(exc)
        return ""

    def _safe_json_call(
        self,
        prompt: str,
        model_name: str,
        role: str,
        required_list_field: str,
    ) -> tuple[str, Optional[Dict]]:
        """Retry a role until it returns the required JSON object schema."""
        self._last_call_error = None
        last_raw = ""
        for _attempt in range(self.max_call_attempts):
            try:
                response = self._invoke_llm(prompt, role)
            except Exception as exc:
                self._last_call_error = self._format_call_error(exc)
                continue

            if not response:
                self._last_call_error = "LLM returned an empty response"
                continue
            last_raw = response
            parsed = self._parse_json(response)
            values = parsed.get(required_list_field) if parsed else None
            if isinstance(values, list) and all(
                isinstance(item, dict) for item in values
            ):
                self._last_call_error = None
                return response, parsed
            self._last_call_error = (
                f"Invalid {role} response: expected JSON object with "
                f"a '{required_list_field}' list of objects"
            )
        return last_raw, None

    def _invoke_llm(self, prompt: str, role: str) -> str:
        """Invoke callables with only the optional arguments they support."""
        import inspect

        kwargs = {}
        try:
            parameters = inspect.signature(self.llm_call).parameters
        except (TypeError, ValueError):
            parameters = {}
        accepts_kwargs = any(
            parameter.kind == inspect.Parameter.VAR_KEYWORD
            for parameter in parameters.values()
        )
        if "role" in parameters or accepts_kwargs:
            kwargs["role"] = role
        if "timeout_seconds" in parameters or accepts_kwargs:
            kwargs["timeout_seconds"] = self.timeout
        return self.llm_call(prompt, **kwargs)

    @staticmethod
    def _format_call_error(exc: Exception) -> str:
        """Bound exception text so logs and JSON reports cannot grow unbounded."""
        message = str(exc).replace("\n", " ")[:300]
        return f"{type(exc).__name__}: {message}" if message else type(exc).__name__

    @staticmethod
    def _emit_progress(
        callback,
        role: str,
        parsed_json: Optional[Dict],
        raw_text: Optional[str],
        log: List[Dict[str, Any]],
    ) -> None:
        """Keep presentation callback failures from aborting the diagnosis."""
        if callback is None:
            return
        try:
            callback(role, parsed_json, raw_text)
        except Exception as exc:
            log.append({
                "role": "progress_callback",
                "source_role": role,
                "error": DebateEngine._format_call_error(exc),
            })

    @staticmethod
    def _parse_json(raw: str) -> Optional[Dict]:
        """Robust JSON parsing from LLM output."""
        parsed = parse_json_safe(raw)
        if parsed is None or set(parsed) == {"error"}:
            return None
        return parsed
