#!/usr/bin/env python3
"""Build the v0 audit-trajectory dataset (``trajectories/v0``).

The benchmark and negative splits are generated by running the deterministic
analysis over the committed corpora; the real-world split is curated from
public issues/PRs (``sources/real_world.yaml``). Output is sorted and
redacted; the manifest records a SHA-256 of the JSONL.

This is a maintainer tool, not a CI step: it needs the full parser set (Go
included). CI validates the committed output instead.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any, Dict, List

import yaml

import smartbench
from smartbench.benchmarks.runner import load_benchmark_manifest
from smartbench.core import AnalysisSession, UnifiedDiagnosticConfig
from smartbench.trajectory import SCHEMA_VERSION, redact_document, validate_document

FIXED_TIME = "2026-10-21T00:00:00Z"
SPLIT_ORDER = {"real_world": 0, "benchmark": 1, "negative": 2}
DATASET_SCHEMA = "smartbench.dataset/v1"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="Repository root")
    parser.add_argument("--out", default="trajectories/v0", help="Output directory")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    output = (root / args.out).resolve()
    documents: List[Dict[str, Any]] = []

    consent = _load_consent(output / "consent.json")
    sources_path = output / "sources" / "real_world.yaml"
    real_sources = _load_real_sources(sources_path) if sources_path.is_file() else []
    approved = {
        case_id
        for case_id, case in consent.items()
        if case.get("status") == "granted" and str(case.get("evidence") or "").strip()
    }
    real_sources = [case for case in real_sources if str(case.get("id")) in approved]
    documents.extend(_real_world_documents(real_sources, tool_version=smartbench.__version__))

    real_manifest = root / "benchmarks" / "real" / "manifest.yaml"
    negative_manifest = root / "benchmarks" / "negative" / "manifest.yaml"
    documents.extend(
        _corpus_documents(real_manifest, split="benchmark", root=root)
    )
    documents.extend(
        _corpus_documents(negative_manifest, split="negative", root=root)
    )

    documents.sort(
        key=lambda doc: (
            SPLIT_ORDER.get(str(doc.get("config", {}).get("split")), 99),
            str(doc.get("trajectory_id", "")),
        )
    )
    for document in documents:
        document["finding_signature"] = _finding_signature(document.get("findings") or [])
        deterministic = document.get("deterministic") or {}
        deterministic["finding_signature"] = _finding_signature(
            deterministic.get("findings") or []
        )
        document["deterministic"] = deterministic
        errors = validate_document(document)
        if errors:
            raise SystemExit(
                f"invalid trajectory {document.get('trajectory_id')}: {errors}"
            )

    output.mkdir(parents=True, exist_ok=True)
    dataset_path = output / "trajectories.jsonl"
    with dataset_path.open("w", encoding="utf-8", newline="\n") as handle:
        for document in documents:
            handle.write(
                json.dumps(document, ensure_ascii=False, sort_keys=True) + "\n"
            )

    splits: Dict[str, int] = {}
    for document in documents:
        split = str(document.get("config", {}).get("split", "unknown"))
        splits[split] = splits.get(split, 0) + 1
    manifest = {
        "schema_version": DATASET_SCHEMA,
        "publication_policy": "explicit-written-consent",
        "consent_file": "consent.json",
        "consent_pending": sum(
            1 for case in consent.values() if case.get("status") == "pending"
        ),
        "consent_declined": sum(
            1 for case in consent.values() if case.get("status") == "declined"
        ),
        "name": "smartbench-audit-trajectories",
        "version": "v0",
        "created": "2026-10-21",
        "license": "CC-BY-4.0",
        "trajectory_schema": SCHEMA_VERSION,
        "tool_version": smartbench.__version__,
        "generator": "tools/build_trajectories_v0.py",
        "documents": len(documents),
        "splits": dict(sorted(splits.items())),
        "sha256": hashlib.sha256(dataset_path.read_bytes()).hexdigest(),
        "notes": (
            "Deterministic audit trajectories. The benchmark and negative splits "
            "contain no LLM conclusions; the real-world split is curated from "
            "public issues/PRs with runtime verification."
        ),
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(documents)} trajectories to {dataset_path}")
    print(f"splits: {manifest['splits']}")
    return 0


def _load_consent(path: Path) -> Dict[str, Dict[str, Any]]:
    document = json.loads(path.read_text(encoding="utf-8"))
    if document.get("schema_version") != "smartbench.consent/v1":
        raise SystemExit(f"unsupported consent schema in {path}")
    cases = document.get("cases", [])
    if not isinstance(cases, list):
        raise SystemExit(f"invalid consent cases in {path}")
    return {
        str(case.get("id")): case
        for case in cases
        if isinstance(case, dict) and case.get("id")
    }


def _load_real_sources(path: Path) -> List[Dict[str, Any]]:
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(document, dict) or not isinstance(document.get("cases"), list):
        raise SystemExit(f"invalid real-world source file: {path}")
    return [case for case in document["cases"] if isinstance(case, dict)]


def _real_world_documents(
    cases: List[Dict[str, Any]], *, tool_version: str
) -> List[Dict[str, Any]]:
    documents: List[Dict[str, Any]] = []
    for case in cases:
        case_id = str(case.get("id") or "")
        reference = str(case.get("reference") or "")
        finding = _finding(
            rule_id=str(case.get("rule_id") or ""),
            file_path=str(case.get("file_path") or ""),
            line_start=int(case.get("line_start") or 0),
            title=str(case.get("title") or ""),
            confidence=None,
        )
        document = _base_document(
            trajectory_id=_stable_id("real_world", case_id),
            project_name=str(case.get("repository") or case_id),
            languages=[str(case.get("language") or "")],
            config={
                "split": "real_world",
                "case_id": case_id,
                "category": str(case.get("category") or ""),
                "outcome": str(case.get("outcome") or ""),
                "disclosure": str(case.get("disclosure") or ""),
            },
            findings=[finding],
            tool_version=tool_version,
        )
        document["stages"] = [{"name": "human-verified", "status": "ok"}]
        document["deterministic"] = {
            "findings": [finding],
            "errors": [],
        }
        document["adjudication"] = [
            {
                "label": str(case.get("adjudication") or "actionable"),
                "reason": str(case.get("verification") or ""),
                "source": reference,
            }
        ]
        document["verification"] = [
            {
                "summary": str(case.get("verification") or ""),
                "reference": reference,
                "commit": str(case.get("commit") or ""),
            }
        ]
        document["provenance"] = {
            "reference": reference,
            "disclosure": str(case.get("disclosure") or ""),
            "outcome": str(case.get("outcome") or ""),
            "location_note": str(case.get("location_note") or ""),
        }
        documents.append(redact_document(document))
    return documents


def _corpus_documents(
    manifest_path: Path, *, split: str, root: Path
) -> List[Dict[str, Any]]:
    cases = load_benchmark_manifest(manifest_path)
    documents: List[Dict[str, Any]] = []
    for case in cases:
        for snapshot in case.snapshots:
            config = UnifiedDiagnosticConfig(
                use_static_rules=bool(case.rule_ids),
                languages=[case.language],
                rule_ids=list(case.rule_ids) or None,
                state_rule_paths=list(case.state_rule_paths),
                min_confidence=snapshot.min_confidence,
                build_evidence_packs=False,
            )
            session = AnalysisSession.analyze(snapshot.path, config)
            findings = _session_findings(session)
            document = _base_document(
                trajectory_id=_stable_id(split, case.case_id, snapshot.label),
                project_name=f"{case.case_id}/{snapshot.label}",
                languages=[case.language],
                config={
                    "split": split,
                    "case_id": case.case_id,
                    "snapshot": snapshot.label,
                    "language": case.language,
                    "expected_rule_ids": sorted(snapshot.expected_rule_ids),
                    "min_confidence": snapshot.min_confidence,
                    "category": str(
                        case.metadata.get("bug_category")
                        or case.metadata.get("category")
                        or ""
                    ),
                    "source_manifest": str(manifest_path.relative_to(root)).replace("\\", "/"),
                },
                findings=findings,
                tool_version=smartbench.__version__,
            )
            document["stages"] = [
                {"name": "deterministic", "status": "ok", "findings": len(findings)}
            ]
            document["deterministic"] = {
                "findings": findings,
                "errors": [
                    str(error)[:300]
                    for error in (getattr(session.result, "errors", None) or [])[:20]
                ],
            }
            documents.append(redact_document(document, project_root=snapshot.path))
    return documents


def _base_document(
    *,
    trajectory_id: str,
    project_name: str,
    languages: List[str],
    config: Dict[str, Any],
    findings: List[Dict[str, Any]],
    tool_version: str,
) -> Dict[str, Any]:
    return {
        "schema_version": SCHEMA_VERSION,
        "trajectory_id": trajectory_id,
        "recorded_at": FIXED_TIME,
        "tool_version": tool_version,
        "project": {
            "name": project_name,
            "root_hash": _stable_id(project_name),
            "languages": [language for language in languages if language],
        },
        "config": config,
        "stages": [],
        "deterministic": {"findings": [], "errors": []},
        "debate": [],
        "findings": findings,
        "adjudication": [],
        "verification": [],
        "human_feedback": [],
        "usage": {},
    }


def _session_findings(session: AnalysisSession) -> List[Dict[str, Any]]:
    findings: List[Dict[str, Any]] = []
    for finding in getattr(session.result, "findings", None) or []:
        location = getattr(finding, "location", None)
        findings.append(
            {
                "rule_id": str(getattr(finding, "rule_id", "") or ""),
                "file_path": _relative(getattr(location, "file_path", "")),
                "line_start": int(getattr(location, "line_start", 0) or 0),
                "title": str(getattr(finding, "rule_name", "") or ""),
                "severity": str(getattr(getattr(finding, "severity", ""), "value", getattr(finding, "severity", "")) or ""),
                "confidence": round(float(getattr(finding, "confidence", 0.0) or 0.0), 4),
                "evidence_ids": [],
            }
        )
    return findings


def _finding(
    *,
    rule_id: str,
    file_path: str,
    line_start: int,
    title: str,
    confidence: float | None,
) -> Dict[str, Any]:
    return {
        "rule_id": rule_id,
        "file_path": _relative(file_path),
        "line_start": line_start,
        "title": title,
        "severity": "warning",
        "confidence": confidence,
        "evidence_ids": [],
    }


def _relative(path: Any) -> str:
    text = str(path or "").replace("\\", "/")
    while text.startswith("./"):
        text = text[2:]
    return text


def _stable_id(*parts: str) -> str:
    return hashlib.sha256(":".join(parts).encode("utf-8")).hexdigest()[:16]


def _finding_signature(findings: List[Dict[str, Any]]) -> str:
    keys = sorted(
        (
            str(item.get("rule_id") or ""),
            str(item.get("file_path") or ""),
            int(item.get("line_start") or 0),
            str(item.get("title") or ""),
        )
        for item in findings
        if isinstance(item, dict)
    )
    return hashlib.sha256(json.dumps(keys, ensure_ascii=False).encode("utf-8")).hexdigest()[:16]


if __name__ == "__main__":
    raise SystemExit(main())
